// build.mjs — 单文件 userscript 构建。
// 步骤: ① vendors/engine.wasm → gzip → base64 → src/generated/wasm-b64.ts (内嵌资产)
//       ② esbuild bundle (ESM 源 → IIFE 产物, userscript 生态约束) + ==UserScript== banner
// 产物: dist/log-skimmer.user.js (安装即完整离线 — wasm 内嵌, 规则 bundle 是唯一网络依赖)。
// wasm 供给切换 (M1 正式产物): 只需替换 vendors/engine.wasm 并更新 vendors/README.md 指纹 — 本脚本零改动。
import { createHash } from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { gzipSync } from 'node:zlib'
import { build } from 'esbuild'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const WASM = path.join(ROOT, 'vendors/engine.wasm')
const GEN_DIR = path.join(ROOT, 'src/generated')
const GEN_FILE = path.join(GEN_DIR, 'wasm-b64.ts')
const OUT = path.join(ROOT, 'dist/log-skimmer.user.js')

const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'))

// ---- ① wasm 内嵌 (gzip+base64: 1.72MB → ~0.55MB, 产物体积省 ~60%) ----
const wasmRaw = fs.readFileSync(WASM)
const gz = gzipSync(wasmRaw, { level: 9 })
const b64 = gz.toString('base64')
fs.mkdirSync(GEN_DIR, { recursive: true })
fs.writeFileSync(
  GEN_FILE,
  `// GENERATED by scripts/build.mjs — do not edit (gitignored).\n// vendored engine.wasm, gzip level 9 + base64. Source/provenance: vendors/README.md\nexport default '${b64}'\n`,
)

// ---- ② userscript header (版本号 SSOT = package.json) ----
const header = `// ==UserScript==
// @name         log-skimmer
// @namespace    https://github.com/luochen1990/log-skimmer
// @version      ${pkg.version}
// @description  CI failure logs, skimmed — inline failure highlights + a skim overlay on GitHub Actions / Forgejo job log pages
// @author       luochen1990
// @license      Apache-2.0
// @homepageURL  https://github.com/luochen1990/log-skimmer
// @match        https://github.com/*/*/actions/runs*
// @match        https://github.com/*/*/commit/*/checks*
// @match        *://*/*/*/actions/runs*
// @grant        GM_xmlhttpRequest
// @grant        GM.setValue
// @grant        GM.getValue
// @grant        GM.deleteValue
// @connect      raw.githubusercontent.com
// @run-at       document-idle
// @noframes
// ==/UserScript==`

await build({
  entryPoints: [path.join(ROOT, 'src/main.ts')],
  bundle: true,
  format: 'iife',
  target: 'es2022',
  platform: 'browser',
  outfile: OUT,
  banner: { js: header },
  legalComments: 'none',
  charset: 'utf8',
  sourcemap: false,
  minify: false, // 保持 TM 编辑器内可读可调; 体积由 wasm 主导, minify 收益趋零
  logLevel: 'info',
})

// ---- 汇报 ----
const outSize = fs.statSync(OUT).size
const sha = createHash('sha256').update(wasmRaw).digest('hex')
console.log(`wasm: raw ${wasmRaw.length} B · gzip ${gz.length} B · base64 ${b64.length} B`)
console.log(`wasm sha256: ${sha}`)
console.log(`userscript: ${OUT} (${outSize} B = ${(outSize / 1024 / 1024).toFixed(2)} MiB)`)
