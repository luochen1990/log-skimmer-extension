// build.mjs — 单文件 userscript 构建。
// 步骤: ① 源构建 wasm (引擎仓 worktree, cargo release) → gzip → base64 →
//          src/generated/wasm-b64.ts (内嵌资产, 头注释登记引擎 commit + sha256 溯源)
//       ② esbuild bundle (ESM 源 → IIFE 产物, userscript 生态约束) + ==UserScript== banner
// 产物: dist/log-skimmer.user.js (安装即完整离线 — wasm 内嵌, 规则 bundle 是唯一网络依赖)。
// wasm 供给 (正式源): 源目录 = 引擎仓 master checkout (cargo + wasm32 工具链
//   经其 devShell 提供 — `nix develop $SRC -c just check` 在本仓跑通全链)。
//   LOG_SKIMMER_WASM_SRC 可覆盖 (调试/镜像)。生产 CI 未来的源 = web 仓 CI 自建
//   (runner 装 rust + wasm32 target 后 checkout 引擎仓自建, 不再依赖 /tmp worktree)。

import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { gzipSync } from 'node:zlib'
import { build } from 'esbuild'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const GEN_DIR = path.join(ROOT, 'src/generated')
const GEN_FILE = path.join(GEN_DIR, 'wasm-b64.ts')
const OUT = path.join(ROOT, 'dist/log-skimmer.user.js')

// wasm 源 (引擎仓 worktree); 产物路径 = cargo 默认 target 布局。
const WASM_SRC = process.env.LOG_SKIMMER_WASM_SRC ?? '/home/lc/ws/log-skimmer'
const WASM = path.join(WASM_SRC, 'target/wasm32-unknown-unknown/release/log_skimmer_wasm.wasm')

const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'))

// ---- ① 源构建 wasm (cargo release, 在源目录执行 — Cargo.toml/workspace 在彼处) ----
// 预检源在场: 缺失时 spawn 的 ENOENT 形态指向 "cargo 不在", 真因归因误导。
if (!fs.existsSync(path.join(WASM_SRC, 'Cargo.toml'))) {
  console.error(`wasm 源不存在: ${WASM_SRC} — 设置 LOG_SKIMMER_WASM_SRC 指向引擎仓 checkout (master)`)
  process.exit(1)
}
execFileSync(
  'cargo',
  ['build', '--release', '--locked', '-p', 'log-skimmer-wasm', '--target', 'wasm32-unknown-unknown'],
  {
    cwd: WASM_SRC,
    stdio: 'inherit',
  },
)
const wasmRaw = fs.readFileSync(WASM)
const gz = gzipSync(wasmRaw, { level: 9 })
const b64 = gz.toString('base64')
const sha256 = createHash('sha256').update(wasmRaw).digest('hex')
// 溯源: 引擎源 commit (支持侧对账 "产物对应引擎哪份代码"; dist 不进仓, 本地凭据)。
const engineCommit = execFileSync('git', ['-C', WASM_SRC, 'rev-parse', '--short', 'HEAD'], {
  encoding: 'utf8',
}).trim()
fs.mkdirSync(GEN_DIR, { recursive: true })
fs.writeFileSync(
  GEN_FILE,
  `// GENERATED by scripts/build.mjs — do not edit (gitignored).\n// engine wasm (release, wasm32) from ${WASM_SRC} @ ${engineCommit}, sha256 ${sha256}\n// gzip level 9 + base64\nexport default '${b64}'\n`,
)

// ---- ② userscript header (版本号 SSOT = package.json) ----
const header = `// ==UserScript==
// @name         log-skimmer
// @namespace    https://github.com/luochen1990/log-skimmer
// @version      ${pkg.version}
// @description  CI failure logs, skimmed — inline failure highlights + a skim overlay on GitHub Actions / Forgejo job log pages
// @author       luochen1990
// @license      Apache-2.0
// @homepageURL  https://github.com/luochen1990/log-skimmer
// @match        https://github.com/*/*/actions/runs*
// @match        https://github.com/*/*/commit/*/checks*
// @match        *://*/*/*/actions/runs*
// @grant        GM_xmlhttpRequest
// @grant        GM.setValue
// @grant        GM.getValue
// @grant        GM.deleteValue
// @connect      raw.githubusercontent.com
// @run-at       document-idle
// @noframes
// ==/UserScript==`

await build({
  entryPoints: [path.join(ROOT, 'src/main.ts')],
  bundle: true,
  format: 'iife',
  target: 'es2022',
  platform: 'browser',
  outfile: OUT,
  banner: { js: header },
  legalComments: 'none',
  charset: 'utf8',
  sourcemap: false,
  minify: false, // 保持 TM 编辑器内可读可调; 体积由 wasm 主导, minify 收益趋零
  logLevel: 'info',
})

// ---- 汇报 ----
const outSize = fs.statSync(OUT).size
console.log(`wasm: raw ${wasmRaw.length} B · gzip ${gz.length} B · base64 ${b64.length} B`)
console.log(`wasm sha256: ${sha256} (engine @ ${engineCommit})`)
console.log(`userscript: ${OUT} (${outSize} B = ${(outSize / 1024 / 1024).toFixed(2)} MiB)`)
